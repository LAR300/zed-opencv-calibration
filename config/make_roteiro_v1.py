"""Generates config/roteiro_v1.yaml, the pose script of the brief (R2), and
config/roteiro_metrico_v1.yaml, the metric test (R7). Run: python3 config/make_roteiro_v1.py
Spec: .ai/specs/roteiro-poses/spec.md (R1-R3), .ai/specs/validacao-metrica/spec.md (R2)."""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
FRACTION = {"P": (0.70, 0.80), "M": (0.40, 0.50), "L": (0.20, 0.25)}  # of the image width
GRID = {"TL": (1 / 6, 1 / 6), "TC": (0.5, 1 / 6), "TR": (5 / 6, 1 / 6),
        "ML": (1 / 6, 0.5), "MC": (0.5, 0.5), "MR": (5 / 6, 0.5),
        "BL": (1 / 6, 5 / 6), "BC": (0.5, 5 / 6), "BR": (5 / 6, 5 / 6)}
EDGES = {"EL": (0.0, 0.5), "ER": (1.0, 0.5), "ET": (0.5, 0.0), "EB": (0.5, 1.0)}  # half outside
TILTS = {"Hp35": (35, 0), "Hm35": (-35, 0), "Vp35": (0, 35), "Vm35": (0, -35)}


def pose(pid, block, dist, center, tilt=(0, 0), rotation=0, fraction=None):
    fmin, fmax = fraction or FRACTION[dist]
    return ("  - {id: %s, block: %d, fraction: [%.2f, %.2f], center: [%.4f, %.4f], "
            "tilt_h_deg: %d, tilt_v_deg: %d, rotation_deg: %d}" %
            (pid, block, fmin, fmax, center[0], center[1], tilt[0], tilt[1], rotation))


def roteiro_v1():
    lines = []
    for dist in ("P", "M", "L"):                                     # block 1: 27
        for pos, c in GRID.items():
            lines.append(pose("B1-%s-%s" % (dist, pos), 1, dist, c))
    for pos in ("MC", "TL", "TR", "BL", "BR"):                       # block 2: 20
        for var, tilt in TILTS.items():
            lines.append(pose("B2-M-%s-%s" % (pos, var), 2, "M", GRID[pos], tilt))
    for pos in ("MC", "TL", "BR"):                                   # block 3: 12
        for rot in (0, 90, 180, 270):
            lines.append(pose("B3-P-%s-R%03d" % (pos, rot), 3, "P", GRID[pos], rotation=rot))
    for edge, c in EDGES.items():                                    # block 4: 4
        lines.append(pose("B4-P-%s" % edge, 4, "P", c))
    return lines


def roteiro_metrico(distances_cm=(50, 100, 200, 300), board_mm=660.0, hfov_frac_per_m=2.384):
    """5 pairs centred + 4 at the edges per distance (R7). The expected fraction comes from the
    pinhole width of the image at 1 m (2.384 m for HFOV ~100 deg), +-25%: the distance, measured
    with the instrument, is what matters here."""
    lines = []
    for cm in distances_cm:
        f = board_mm / 1000.0 / (hfov_frac_per_m * cm / 100.0)
        rng = (round(f * 0.75, 2), round(min(2.0, f * 1.25), 2))
        for k in range(1, 6):
            lines.append(pose("MET-%d-MC-%d" % (cm, k), 1, None, GRID["MC"], fraction=rng))
        for pos in ("ML", "MR", "TC", "BC"):
            lines.append(pose("MET-%d-%s-1" % (cm, pos), 2, None, GRID[pos], fraction=rng))
    return lines


def write(name, title, tolerances, lines):
    header = ("# %s\n# Generated by config/make_roteiro_v1.py: edit the generator, not this file.\n"
              "# Fraction: of the image WIDTH taken by the whole target; center: normalised image\n"
              "# position of the target centre; angles in degrees (conventions in\n"
              "# common/pose_script/pose_script.hpp).\n" % title)
    with open(os.path.join(HERE, name), "w") as f:
        f.write(header + "name: %s\ntolerances: %s\nposes:\n" % (name[:-5], tolerances))
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    write("roteiro_v1.yaml", "Pose script v1 (brief R2): 63 poses in 4 blocks",
          "{fraction: 0.05, position: 0.08, angle_deg: 5}", roteiro_v1())
    write("roteiro_metrico_v1.yaml", "Metric test v1 (brief R7): 9 poses per distance",
          "{fraction: 0.05, position: 0.08, angle_deg: 2}", roteiro_metrico())
